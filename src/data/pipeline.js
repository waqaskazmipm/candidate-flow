export const AVATAR_TONES = [
  'indigo',
  'violet',
  'sky',
  'teal',
  'emerald',
  'amber',
  'rose',
]

export function toneForName(name) {
  const total = [...name].reduce((sum, char) => sum + char.charCodeAt(0), 0)
  return AVATAR_TONES[total % AVATAR_TONES.length]
}

